#!/usr/bin/env python3
"""render-doc.py — assemble the t8 results document from generated parts.

The committed results document must not contain a hand-typed table (the t12
precedent: a typed table is a table nobody can re-derive). So the document is
assembled, never authored whole:

* the **prose** is a committed template beside this script
  (`worker-scoped-overhead.template.md`), which owns every claim and caveat;
* ``{{TABLES}}`` is replaced by `examples/worker_scoped_overhead.py`'s own
  ``render_markdown`` output, regenerable from the committed JSONL with
  ``--rebuild-from`` and no rig;
* ``{{WINDOW}}`` is replaced by a table built here from
  `window-log.jsonl` — the idle-window declaration acceptance criterion 3
  requires, rendered from the guard's own records rather than retyped.

Run it after any re-render of the tables::

    python3 render-doc.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
RESULTS = HERE.parent

TEMPLATE = HERE / "worker-scoped-overhead.template.md"
TABLES = RESULTS / "worker-scoped-overhead-tables.md"
WINDOW_LOG = HERE / "window-log.jsonl"
OUT = RESULTS / "worker-scoped-overhead.md"

GENERATED_MARKER = "<!-- generated by "


def window_table(path: Path) -> str:
    """The declared idle window, rendered from the guard's own committed records."""
    if not path.exists():
        return "**ABSENT** — no window log at `window-log.jsonl`.\n"
    rows = [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line]
    lines = [
        "<!-- generated by render-doc.py::window_table from window-log.jsonl "
        "— do not hand-edit -->",
        "",
        "| timestamp | check | verdict | process angle | endpoint angle |",
        "|---|---|---|---|---|",
    ]
    for row in rows:
        angles = {angle["angle"]: angle for angle in row["angles"]}
        lines.append(
            f"| `{row['at']}` | {row['label'] or '—'} | **{row['verdict']}** "
            f"| {angles['processes']['detail']} | {angles['endpoint']['detail']} |"
        )
    return "\n".join(lines) + "\n"


def main() -> int:
    for path in (TEMPLATE, TABLES):
        if not path.exists():
            print(f"missing: {path}", file=sys.stderr)
            return 1

    # Drop everything above the first `###`: the generated file carries its own
    # banner and its own H1 so it lints as a standalone document, and the
    # assembled page must keep exactly one H1 — its own — and one provenance
    # banner, not two.
    table_lines = TABLES.read_text(encoding="utf-8").splitlines()
    first_table = next(
        (index for index, line in enumerate(table_lines) if line.startswith("### ")), None
    )
    if first_table is None:
        print(f"no '### ' heading found in {TABLES}", file=sys.stderr)
        return 1
    tables = "\n".join(table_lines[first_table:]).strip()
    if any(line.startswith(GENERATED_MARKER) for line in table_lines[first_table:]):
        print("unexpected generator banner below the first table", file=sys.stderr)
        return 1

    document = TEMPLATE.read_text(encoding="utf-8")
    document = document.replace("{{TABLES}}", tables)
    document = document.replace("{{WINDOW}}", window_table(WINDOW_LOG).strip())
    OUT.write_text(document, encoding="utf-8")
    print(f"wrote {OUT}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
