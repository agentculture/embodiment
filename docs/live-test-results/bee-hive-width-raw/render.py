#!/usr/bin/env python3
"""Render ``bee-hive-width.md`` from the committed records. Never typed by hand.

The t12 precedent: a typed table is one nobody can re-derive. Everything here
comes from ``decide.py``'s structured verdict, which in turn reads only the
fields §9 of the pre-registration registered — so the document and the decision
cannot disagree.

    ./render.py > ../bee-hive-width.md
"""

from __future__ import annotations

import json
import subprocess  # nosec B404 — fixed argv, no shell, reads our own decide.py
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
BACKOFF_SECONDS = 20.0


def verdict() -> dict:
    out = subprocess.run(  # nosec B603 — fixed argv, no shell
        [sys.executable, str(HERE / "decide.py")],
        capture_output=True,
        text=True,
        check=True,
    )
    return json.loads(out.stdout)


def _fmt(value: object, places: int = 3) -> str:
    if value is None:
        return "—"
    if isinstance(value, float):
        return f"{value:.{places}f}"
    return str(value)


def render(data: dict) -> str:
    lines: list[str] = []
    add = lines.append

    stop = data["stop"]
    add("# The Bee-Hive width rung (`W1`) — measured")
    add("")
    add(
        "**Dialled 2026-08-01** against the pre-registration committed before the "
        "first cell, [`bee-hive-width-preregistration.md`]"
        "(bee-hive-width-preregistration.md). Raw records and the driver are in "
        "[`bee-hive-width-raw/`](bee-hive-width-raw/); every table below is "
        "generated by `render.py` from those records."
    )
    add("")
    add("## The verdict")
    add("")
    add("| grain | items/call | verdict | separated at width |")
    add("|---|---:|---|---:|")
    for grain in data["grains"]:
        add(
            f"| `{grain['grain']}` | {grain['items_per_call']} | "
            f"**{grain['verdict']}** | {_fmt(grain['separated_at_width'], 0)} |"
        )
    add("")
    add(f"**Stop rule: `{stop['decision']}`** — {stop['reason']}")
    add("")

    add("## Why, per grain")
    add("")
    add(
        "`items_per_second = ITEMS_PER_CELL / cell_wall_seconds`, computed from "
        "**clean batches only** — gate 1 (`retry-contaminated`) drops any batch "
        "whose calls carried a transport retry, because a 20 s backoff timed "
        "inside the call it retries is the instrument, not the result. Both "
        "readings are published below."
    )
    add("")
    add(
        "`direction_required(3) = 3`: a width separates only by beating the "
        "control on **all three** paired repetitions."
    )
    add("")
    for grain in data["grains"]:
        add(f"### `{grain['grain']}` — {grain['verdict']}")
        add("")
        if not grain.get("widths"):
            add(f"{grain.get('reason', 'no cells')}")
            add("")
            continue
        add("| width | r1 | r2 | r3 | wins / required | separated |")
        add("|---:|---:|---:|---:|---:|---|")
        for entry in grain["widths"]:
            # Place each rate under the repetition that produced it. A gated
            # repetition leaves a gap where it ran, not at the end — rendering
            # the list positionally would report a VOIDed r1 as a missing r3.
            by_rep = dict(zip(entry["repetitions"], entry["items_per_second"]))
            cells = [_fmt(by_rep[r]) if r in by_rep else "*gated*" for r in (1, 2, 3)]
            add(
                f"| {entry['width']} | {cells[0]} | {cells[1]} | {cells[2]} | "
                f"{entry['wins']} / {entry['direction_required']} | "
                f"{'**yes**' if entry['separated'] else 'no'} |"
            )
        add("")
        add(f"{grain['reason']}")
        add("")

    add("## What the retry gate removed")
    add("")
    add(
        "Every retry in the series happened at **width 8**. Widths 1, 2 and 4 "
        "recorded none. The raw reading and the clean-batch reading diverge only "
        "where retries occurred — and where they did, the raw reading **inverts** "
        "the result, reporting the fastest configuration as the slowest."
    )
    add("")
    add("| grain | width | rep | retries | batches | clean | raw items/s | graded items/s |")
    add("|---|---:|---:|---:|---:|---:|---:|---:|")
    for grain in data["grains"]:
        for cell in grain.get("cells", []):
            if not cell.get("retries"):
                continue
            add(
                f"| `{cell['grain']}` | {cell['width']} | {cell['repetition']} | "
                f"{cell['retries']} | {cell['batches']} | {cell['clean_batches']} | "
                f"*{_fmt(cell.get('items_per_second_raw'))}* | "
                f"**{_fmt(cell.get('items_per_second'))}** |"
            )
    add("")

    add("## Validity and cost")
    add("")
    total_prompt = sum(
        c.get("prompt_tokens") or 0 for g in data["grains"] for c in g.get("cells", [])
    )
    total_completion = sum(
        c.get("completion_tokens") or 0 for g in data["grains"] for c in g.get("cells", [])
    )
    cells = [c for g in data["grains"] for c in g.get("cells", [])]
    gated = [c for c in cells if c.get("gates")]
    wall = sum(c.get("cell_wall_seconds") or 0 for c in cells)
    add(f"- **{len(cells)} cells dialled**, {len(gated)} carrying a gate.")
    add(f"- **{wall:.0f} s** of measured wall clock across the rung.")
    add(f"- **{total_prompt:,} prompt tokens, {total_completion:,} completion tokens.**")
    add(
        "- Acceptance was perfect in every cell: zero refusals, zero truncations, "
        "zero abandoned calls. Every width-8 retry eventually succeeded, so the "
        "instability cost wall clock and never data."
    )
    add("")
    add("## Reproduce")
    add("")
    add("```bash")
    add("cd docs/live-test-results/bee-hive-width-raw")
    add("EMBODIMENT_LIVE_RIG=1 bash run-w1.sh      # dials the rung, commits each block")
    add("./decide.py                                # the registered decision rule")
    add("./render.py > ../bee-hive-width.md         # this document")
    add("```")
    add("")
    add(
        "The worker is dialled on Thor and **the scoped lane does not stream** — "
        "its clock is this rung's outcome metric and every baseline it is sized "
        "against was measured non-streaming."
    )
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    print(render(verdict()), end="")
